/** 某大类的 Hook 摘要（注入提示词） */
export function hooksDigestForCat(cat) {
  return HOOKS.filter((h) => h.cat === cat)
    .map((h) => `${h.id} ${h.name}「${h.tpl}」例：${h.ex}`)
    .join('\n');
}

export function hookById(id) {
  return HOOKS.find((h) => h.id === id);
}
